"""Write docs/RESULTS.md from SAVED result files only (no new experiments).

For every available TEST measurement file it computes (once, cached in results/model_eval/test_summary_<name>.csv)
the per-kind/per-dose summary, then tabulates CD at the selection dose (inside exposure range) and
precision at 2 and 64 frames. Multi-seed rows report mean and min..max over the seeds that exist and say so.
"""
import glob
import json
import os
import sys
import time

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
import evaluate as ev  # noqa: E402
from data_lithobench import load_config  # noqa: E402

GROUPS = [  # label, meas-name patterns (seed 1 first), note
    ("Classical (tuned on val, calibrated offset)", ["classical_est"], ""),
    ("U-Net, SEM+CAD", ["screen_conv_cad_s1__learned", "confirm_conv_cad_s2__learned", "confirm_conv_cad_s3__learned"], ""),
    ("DCNv2, SEM+CAD", ["screen_dcnv2_cad_s1__learned"], ""),
    ("DCNv3, SEM+CAD (val-selected)", ["screen_dcnv3_cad_s1__learned", "confirm_dcnv3_cad_s2__learned", "confirm_dcnv3_cad_s3__learned"], ""),
    ("DCNv4 (reimpl.), SEM+CAD", ["screen_dcnv4_cad_s1__learned", "confirm_dcnv4_cad_s2__learned", "confirm_dcnv4_cad_s3__learned"], ""),
    ("DCNv3, SEM only (CAD test)", ["cadtest_dcnv3_semonly_s1__learned", "cadtest_dcnv3_semonly_s2__learned", "cadtest_dcnv3_semonly_s3__learned"], ""),
    ("DCNv3 + 1D refine, SEM+CAD", ["screen_dcnv3_cad_s1__refine"], ""),
]


def test_summary(cfg, name, tr):
    out = os.path.join(ROOT, "results", "model_eval", f"test_summary_{name}.csv")
    if os.path.exists(out):
        return pd.read_csv(out)
    path = os.path.join(ROOT, "results", "raw", "meas", "test", name + ".pkl.gz")
    if not os.path.exists(path):
        return None
    s = ev.summarize(cfg, ev.load_meas(cfg, "test", name), tr, name, n_boot=1000)
    s.to_csv(out, index=False)
    return s


def pick(s, kind, dose, col):
    r = s[(s.kind == kind) & (s.dose == dose)]
    return float(r[col].iloc[0]) if len(r) else np.nan


def fmt(vals, d=3):
    v = [x for x in vals if np.isfinite(x)]
    if not v:
        return "n/a"
    if len(v) == 1:
        return f"{v[0]:.{d}f}"
    return f"{np.mean(v):.{d}f} ({min(v):.{d}f}..{max(v):.{d}f})"


def main():
    cfg = load_config()
    tr = ev.load_truth(cfg, "test")
    dose = cfg["eval"]["selection_dose"]
    L = [f"# Results snapshot ({time.strftime('%Y-%m-%d %H:%M')} IST)", "",
         "All CD/EPE numbers come from SIMULATED SEM images (a controlled forward model, not a real CD-SEM).",
         "TMU-style = 3 x residual sd about the OLS line of measured vs simulated truth; reference uncertainty taken as 0 (truth is exact).",
         "Seed counts are given per row. A row with 1 seed is a SINGLE-SEED result (no seed spread). Ranges show min..max over seeds; no 3-seed confidence is implied where fewer seeds exist.",
         "Generated by tools/results_snapshot.py from saved files only.", "",
         f"## Test set (StdMetal 271 + StdContactTest 165 tiles; frozen configs; estimated registration) - CD gauges, {dose} frames, inside exposure range", "",
         "| Method | seeds on test | slope | offset (nm) | bias (nm) | TMU-style 3s (nm) | precision 3s @2 fr (nm) | precision 3s @64 fr (nm) | fail rate | contact TMU-style (nm) | EPE1d TMU-style (nm) |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    status = []
    for label, names, _ in GROUPS:
        ss = [(n, test_summary(cfg, n, tr)) for n in names]
        have = [(n, s) for n, s in ss if s is not None]
        status.append((label, [n for n, s in ss if s is None]))
        if not have:
            L.append(f"| {label} | 0 (not evaluated yet) | | | | | | | | | |")
            continue
        g = lambda k, d_, c: [pick(s, k, d_, c) for _, s in have]  # noqa: E731
        L.append(f"| {label} | {len(have)}{' (single seed)' if len(have) == 1 and not label.startswith('Classical') else ''} | "
                 f"{fmt(g('cd', dose, 'inside_slope'))} | {fmt(g('cd', dose, 'inside_offset'), 2)} | {fmt(g('cd', dose, 'inside_bias'), 2)} | "
                 f"{fmt(g('cd', dose, 'inside_tmu3s'), 2)} | {fmt(g('cd', 2, 'prec_3s'), 2)} | {fmt(g('cd', 64, 'prec_3s'), 2)} | "
                 f"{fmt(g('cd', dose, 'inside_fail_rate'))} | {fmt(g('contact', dose, 'inside_tmu3s'), 2)} | {fmt(g('epe1d', dose, 'inside_tmu3s'), 2)} |")
    L += ["", "Bootstrap 95% CIs (tile resampling, seed 1 / single run) are in results/model_eval/test_summary_<name>.csv (columns inside_tmu3s_ci, inside_slope_ci, prec_3s_ci).", ""]
    # outside range + registration decomposition
    L += ["## Outside the training exposure range and registration (test, CD, 64 frames)", "",
          "| Method | outside slope | outside TMU-style (nm) | outside fail rate | EPE1d TMU-style @8 fr (nm) |", "|---|---|---|---|---|"]
    for label, name in (("Classical, estimated reg", "classical_est"), ("Classical, oracle reg", "classical_oracle"),
                        ("DCNv3 s1, estimated reg", "screen_dcnv3_cad_s1__learned"), ("DCNv3 s1, oracle reg", "screen_dcnv3_cad_s1_oraclereg__learned")):
        s = test_summary(cfg, name, tr)
        if s is None:
            L.append(f"| {label} | not evaluated yet | | | |"); continue
        L.append(f"| {label} | {pick(s, 'cd', 64, 'outside_slope'):.3f} | {pick(s, 'cd', 64, 'outside_tmu3s'):.2f} | "
                 f"{pick(s, 'cd', 64, 'outside_fail_rate'):.3f} | {pick(s, 'epe1d', 8, 'inside_tmu3s'):.2f} |")
    # validation screening
    vs = os.path.join(ROOT, "results", "model_eval", "val_screening.csv")
    if os.path.exists(vs):
        v = pd.read_csv(vs)
        L += ["", "## VALIDATION screening (model selection; seed 1 each; full 120-tile val; selection metric = mean TMU-style CD+contact @8 fr)", "",
              "| name | selection metric (nm) | 95% CI | paired diff vs best (CI) | fail rate |", "|---|---|---|---|---|"]
        for _, r in v.iterrows():
            L.append(f"| {r['name']} | {r.sel_metric:.3f} | {r.sel_ci} | {r.diff_vs_best:+.3f} ({r.diff_ci_lo:+.3f}..{r.diff_ci_hi:+.3f}) | {r.fail_rate:.3f} |")
    # Carinthia
    cj = os.path.join(ROOT, "results", "carinthia", "carinthia_summary.json")
    if os.path.exists(cj):
        L += ["", "## Carinthia-S real SEM (defect segmentation only; SINGLE-SEED, seed 1 for every operator)", "",
              "See results/carinthia/carinthia_summary.json and carinthia_per_class.csv. No CD/EPE truth exists for these images."]
    # M8
    mj = os.path.join(ROOT, "results", "cuda_kernel", "summary.json")
    if os.path.exists(mj):
        L += ["", "## C++/CUDA edge refinement (M8)", "", "See results/cuda_kernel/parity.csv, benchmark.csv, kernel_runtime.png (exclusive GPU benchmark, 2026-11-04 19:38-19:40)."]
    L += ["", "## Not yet evaluated / paused", ""]
    for label, miss in status:
        if miss:
            L.append(f"- {label}: missing {', '.join(miss)}")
    open(os.path.join(ROOT, "docs", "RESULTS.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
